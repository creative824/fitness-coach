/**
 * Builds src/content/food-db.ts from sources.mjs and the USDA FoodData Central SR Legacy CSVs.
 * Usage: node scripts/food-db/generate.mjs <folder with food.csv and food_nutrient.csv>
 */
import fs from "node:fs";
import path from "node:path";
import { FOOD_SOURCES } from "./sources.mjs";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/food-db/generate.mjs <SR Legacy CSV folder>");

function* rows(file) {
  const lines = fs.readFileSync(path.join(dir, file), "utf8").split("\n");
  const head = lines[0].split(",").map((h) => h.replace(/"/g, ""));
  for (const line of lines.slice(1)) {
    if (!line.trim()) continue;
    const cells = [...line.matchAll(/"((?:[^"]|"")*)"|([^,]*)/g)].filter((m, i, all) => m.index === 0 || line[m.index - 1] === ",").map((m) => (m[1] ?? m[2] ?? "").replace(/""/g, '"'));
    yield Object.fromEntries(head.map((h, i) => [h, cells[i]]));
  }
}

const wanted = new Set(FOOD_SOURCES.filter((f) => typeof f.src === "number").map((f) => String(f.src)));
const desc = new Map();
for (const r of rows("food.csv")) if (wanted.has(r.fdc_id)) desc.set(r.fdc_id, r.description);
const NUT = { 1008: "kcal", 1003: "p", 1005: "c", 1004: "f" };
const values = new Map();
for (const r of rows("food_nutrient.csv")) {
  const k = NUT[r.nutrient_id];
  if (!k || !wanted.has(r.fdc_id)) continue;
  values.set(r.fdc_id, { ...values.get(r.fdc_id), [k]: Number(r.amount) });
}

const ids = new Set();
const names = new Map();
const out = FOOD_SOURCES.map((f) => {
  if (ids.has(f.id)) throw new Error(`duplicate id ${f.id}`);
  ids.add(f.id);
  for (const n of f.he) {
    const key = n.replace(/['"׳״`’]/g, "");
    if (names.has(key) && names.get(key) !== f.id) throw new Error(`name "${n}" is in ${names.get(key)} and ${f.id}`);
    names.set(key, f.id);
  }
  if (!f.u[f.d[0]]) throw new Error(`${f.id}: default unit ${f.d[0]} has no weight`);
  let v;
  let src;
  if (typeof f.src === "number") {
    v = values.get(String(f.src));
    if (!v || v.kcal === undefined) throw new Error(`${f.id}: USDA ${f.src} not found`);
    src = `USDA ${f.src}: ${desc.get(String(f.src))}`;
  } else {
    const [kcal, p, c, fat] = f.src;
    v = { kcal, p, c, f: fat };
    src = "IL";
  }
  const r1 = (x) => Math.round((x ?? 0) * 10) / 10;
  return { id: f.id, he: f.he, kcal: Math.round(v.kcal), p: r1(v.p), c: r1(v.c), f: r1(v.f), u: f.u, d: f.d, ...(f.x ? { x: f.x } : {}), src };
});

const file = `/**
 * GENERATED by scripts/food-db/generate.mjs from scripts/food-db/sources.mjs. Do not edit by hand.
 *
 * ${out.length} foods. Values per 100 g (1 ml = 1 g for drinks). "USDA n" is a FoodData Central
 * SR Legacy record (public domain); "IL" is a typical Israeli product label or recipe, rounded.
 */
export interface DbFood {
  id: string;
  /** Hebrew names; the first one is shown. */
  he: string[];
  kcal: number;
  p: number;
  c: number;
  f: number;
  /** Grams per household unit. */
  u: Partial<Record<string, number>>;
  /** Default portion when no amount is given: [unit, quantity]. */
  d: [string, number];
  x?: string[];
  src: string;
}

export const FOOD_DB: DbFood[] = ${JSON.stringify(out, null, 0).replace(/\},\{/g, "},\n  {").replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")};
`;
fs.writeFileSync(new URL("../../src/content/food-db.ts", import.meta.url), file);
console.log(`wrote ${out.length} foods (${out.filter((f) => f.src !== "IL").length} from USDA)`);
